def write_csv(name,header,rows):
 p=ROOT/'electronics'/name; p.parent.mkdir(exist_ok=True)
 with p.open('w',encoding='utf-8-sig',newline='') as f:
  w=csv.writer(f); w.writerow(header); w.writerows(rows)

